// Camera control checks with synthetic input: trackpad pan, pinch zoom, mouse wheel, drag pan, orbit, click still builds.
import { chromium } from "playwright";
const browser = await chromium.launch({ args: ["--use-angle=metal"] });
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
page.on("pageerror", (e) => console.log("[pageerror]", e.message));
await page.goto("http://localhost:5173/?nocoach&test");
await page.waitForSelector("#loading.gone", { timeout: 90000 });
await page.waitForTimeout(3000);
const cam = () => page.evaluate(() => window.__sb.cam());
const wheel = (o) => page.evaluate((o) => { const el = document.querySelector("#scene canvas"); el.dispatchEvent(new WheelEvent("wheel", { bubbles: true, cancelable: true, clientX: 720, clientY: 450, ...o })); }, o);
const settle = () => page.waitForTimeout(400);
console.log("start      ", JSON.stringify(await cam()));
for (let k = 0; k < 10; k++) await wheel({ deltaX: 0, deltaY: 12.5 });
await settle(); console.log("trackpad↑  ", JSON.stringify(await cam()), "(pans, dist unchanged)");
for (let k = 0; k < 10; k++) await wheel({ deltaX: 0, deltaY: -6.3, ctrlKey: true });
await settle(); console.log("pinch out  ", JSON.stringify(await cam()), "(closer)");
for (let k = 0; k < 3; k++) await wheel({ deltaX: 0, deltaY: 100 });
await settle(); console.log("wheel ×3   ", JSON.stringify(await cam()), "(farther)");
for (let k = 0; k < 60; k++) await wheel({ deltaX: 0, deltaY: 100 });
await settle(); console.log("wheel ×60  ", JSON.stringify(await cam()), "(clamped at max)");
for (let k = 0; k < 200; k++) await wheel({ deltaX: 0, deltaY: -50, ctrlKey: true });
await settle(); console.log("pinch ×200 ", JSON.stringify(await cam()), "(clamped at min)");
await page.click("[data-act='recenter']"); await settle();
console.log("recenter   ", JSON.stringify(await cam()));
await page.mouse.move(700, 500); await page.mouse.down(); for (let k = 1; k <= 10; k++) await page.mouse.move(700 + k * 20, 500 + k * 5); await page.mouse.up(); await settle();
console.log("left drag  ", JSON.stringify(await cam()), "(pans)");
await page.mouse.move(700, 500); await page.mouse.down({ button: "right" }); for (let k = 1; k <= 10; k++) await page.mouse.move(700 + k * 15, 500 - k * 10); await page.mouse.up({ button: "right" }); await settle();
console.log("right drag ", JSON.stringify(await cam()), "(orbits, polar clamped)");
for (let k = 0; k < 40; k++) await wheel({ deltaX: 60, deltaY: 60 });
await settle(); console.log("pan ×40    ", JSON.stringify(await cam()), "(target clamped near town)");
await page.click("[data-act='recenter']"); await settle(); await page.waitForTimeout(400);
const b = (await page.evaluate(() => window.__sb.blocks())).find((x) => !x.fixed && x.p);
const before = await page.textContent(".bar-row:nth-child(2) .bar-val");
await page.locator("[data-tool='housing']").click();
await page.mouse.click(b.p.x, b.p.y + 20); await page.waitForTimeout(1200);
console.log("click builds:", before, "→", await page.textContent(".bar-row:nth-child(2) .bar-val"));
await page.screenshot({ path: "/tmp/sb-shots/r17-cam.png" });
await browser.close();
